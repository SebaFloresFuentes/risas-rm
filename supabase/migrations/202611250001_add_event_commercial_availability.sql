create or replace function public.radarrisas_sync_event_sold_out_compatibility_v1()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    if new.sold_out is true then
      new.availability_status := 'sold_out';
    else
      new.sold_out := new.availability_status = 'sold_out';
    end if;
    return new;
  end if;

  if new.availability_status is distinct from old.availability_status then
    new.sold_out := new.availability_status = 'sold_out';
  elsif new.sold_out is distinct from old.sold_out then
    new.availability_status := case
      when new.sold_out then 'sold_out'
      else 'unknown'
    end;
    new.availability_verified_at := null;
  end if;

  return new;
end
$$;

revoke all on function public.radarrisas_sync_event_sold_out_compatibility_v1()
  from public, anon, authenticated;

do $$
begin
  if not exists (
    select 1
    from pg_trigger
    where tgname = 'radarrisas_events_sync_sold_out_v1'
      and tgrelid = 'public.events'::regclass
      and not tgisinternal
  ) then
    create trigger radarrisas_events_sync_sold_out_v1
    before insert or update of sold_out, availability_status
    on public.events
    for each row
    execute function public.radarrisas_sync_event_sold_out_compatibility_v1();
  end if;
end
$$;

